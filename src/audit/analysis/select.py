"""Run selection by plan/call-id membership (Round 14).

`run_id.str.contains("phase3")` style filters are WRONG in two directions:
they admit phase-4 rows and phase-3-era repair runs (`repair2-*` names carry no
`phase3` substring), and they cannot separate phase-4 arms. Selection is by
call-id membership. Two id sources, in order of authority:

1. LOG-DERIVED ids: every run's manifest names the plan it executed; a run's
   call_ids belong to that plan's stem. This is authoritative for historical
   runs whose plan parquet can no longer be regenerated byte-identically
   (phase-3 direct-contrast cells: the name-pair scheme was fixed after the
   run, so regenerated ids differ from logged ones).
2. PLAN ids (data/plans, pinned to historical prompt versions): used for stems
   never run and for arm-level splits within phase 4 (sysarm is not logged).
"""
from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import pandas as pd

PLANS = Path("data/plans")
RUNS = Path("runs")

_MAIN_STEMS = ("pilot", "e1_scoring", "e2_paired", "e3_ranking", "e4_jd_context",
               "phase2_e123", "phase2_e4")
_P3_STEMS = ("phase3_main", "phase3_pilot", "phase3_lawyer", "phase3_manip")
_P4_STEMS = ("phase4_main",)


@lru_cache(maxsize=1)
def _logged_ids_by_stem() -> dict[str, set]:
    """stem -> call_ids logged by runs whose manifest names that plan.

    Repair runs carry a 'plan' only if the repair CLI wrote one; otherwise
    their rows are attributed to the stem of the call's first attempt (the
    repair row's call_id already appears in the original run).
    """
    out: dict[str, set] = {}
    for mf in sorted(RUNS.glob("*/manifest.json")):
        try:
            m = json.loads(mf.read_text())
        except (json.JSONDecodeError, OSError):
            continue
        plan = m.get("plan")
        if not plan:
            continue
        stem = Path(str(plan)).stem
        log = mf.parent / "logs.jsonl"
        if not log.exists():
            continue
        ids = out.setdefault(stem, set())
        with open(log) as fh:
            for line in fh:
                if '"call_id"' not in line:
                    continue
                try:
                    r = json.loads(line)
                except json.JSONDecodeError:
                    continue
                if r.get("call_id"):
                    ids.add(r["call_id"])
    return out


@lru_cache(maxsize=None)
def _plan_ids(*stems: str) -> frozenset:
    ids: set[str] = set()
    for stem in stems:
        p = PLANS / f"{stem}.parquet"
        if p.exists():
            ids.update(pd.read_parquet(p, columns=["call_id"])["call_id"])
    return frozenset(ids)


def _stem_ids(*stems: str) -> frozenset:
    """Logged ids (authoritative) ∪ plan ids (covers never-run cells)."""
    logged = _logged_ids_by_stem()
    ids: set[str] = set()
    for s in stems:
        ids |= logged.get(s, set())
    return frozenset(ids | set(_plan_ids(*stems)))


def main_run_ids() -> frozenset:
    """Call ids of the main-run experiments (phase 1 + phase 2)."""
    return _stem_ids(*_MAIN_STEMS)


def phase3_ids() -> frozenset:
    """Call ids of all phase-3 runs (main, pilot, lawyer rerun, manip)."""
    return _stem_ids(*_P3_STEMS)


def phase4_ids(arm: str | None = None) -> frozenset:
    """Call ids of the phase-4 experiment; optionally one system-prompt arm.

    Arm splits require the plan parquet (sysarm is not logged); the plan's ids
    are verified to match the logged phase-4 call_ids exactly (R11).
    """
    if arm is not None:
        plan = pd.read_parquet(PLANS / "phase4_main.parquet", columns=["call_id", "sysarm"])
        return frozenset(plan.loc[plan.sysarm == arm, "call_id"])
    return _stem_ids(*_P4_STEMS)


def main_run(df: pd.DataFrame) -> pd.DataFrame:
    """Rows whose call_id belongs to the main-run plans."""
    return df[df["call_id"].isin(main_run_ids())]


def phase3(df: pd.DataFrame) -> pd.DataFrame:
    """Rows whose call_id belongs to the phase-3 plans."""
    return df[df["call_id"].isin(phase3_ids())]


def phase4(df: pd.DataFrame, arm: str | None = None) -> pd.DataFrame:
    """Rows whose call_id belongs to the phase-4 plan (optionally one arm)."""
    return df[df["call_id"].isin(phase4_ids(arm))]
